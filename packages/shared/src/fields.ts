export const FIELD_BY_TAG: Readonly<Record<FieldTag, FieldSpec>> = Object.fromEntries(
  FIELDS.map((field) => [field.tag, field]),
) as Record<FieldTag, FieldSpec>;

/** 4 trường nhạy cảm (không log, không trả/hiển thị ở màn hình danh sách). */
export const SENSITIVE_TAGS: readonly SensitiveTag[] = FIELDS.filter((f) => f.sensitive).map(
  (f) => f.tag as SensitiveTag,
);

/** 7 trường Sở Y tế Đồng Nai bắt buộc. */
export const SO_REQUIRED_TAGS: readonly FieldTag[] = FIELDS.filter((f) => f.soRequired).map(
  (f) => f.tag,
);

/** 22 trường BHXH không cho null. */
export const BHXH_REQUIRED_TAGS: readonly FieldTag[] = FIELDS.filter((f) => f.bhxhRequired).map(
  (f) => f.tag,
);

/** 3 trường BHXH cho phép null (`NGAYKHAMLAI`, `LYDO`, `TINHTRANGBENH`). */
export const BHXH_OPTIONAL_TAGS: readonly FieldTag[] = FIELDS.filter((f) => !f.bhxhRequired).map(
  (f) => f.tag,
);

/** 23 trường có mặt trong mẫu Excel nhập liệu (trừ `IDBENHVIEN`, `BENHVIEN`). */
export const TEMPLATE_FIELDS: readonly FieldSpec[] = FIELDS.filter((f) => f.inTemplate);

/** 6 trường bắt buộc có cột trong file Excel import (7 trường Sở bắt buộc trừ `IDBENHVIEN`). */
export const EXCEL_REQUIRED_COLUMNS: readonly FieldTag[] = FIELDS.filter(
  (f) => f.soRequired && f.inTemplate,
).map((f) => f.tag);

/** Tạo bản ghi GKSK rỗng đủ 25 khóa (giá trị chuỗi rỗng). */
export function createEmptyRecord(): GkskRecord {
  const record = {} as GkskRecord;
  for (const tag of FIELD_ORDER) {
    record[tag] = '';
  }
  return record;
}
